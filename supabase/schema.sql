-- Defining and Creating the Enum Types
CREATE TYPE user_role AS ENUM ('attendee', 'organizer', 'admin');
CREATE TYPE verification_status AS ENUM ('pending', 'approved', 'rejected');
CREATE TYPE event_source AS ENUM ('user_submission', 'admin', 'scraped');
CREATE TYPE rsvp_status AS ENUM ('going', 'interested', 'not_going');

-- Public Users Profile Table (synced with Supabase auth.users)
CREATE TABLE public.users (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  name VARCHAR(255),
  email VARCHAR(255),
  role user_role DEFAULT 'attendee'
);

-- Organizer Profiles Table 
CREATE TABLE public.organizer_profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID UNIQUE REFERENCES public.users(id) ON DELETE CASCADE,
  organization_name VARCHAR(255),
  verification_status verification_status DEFAULT 'pending'
);

-- Organizer Verification Requests Table
CREATE TABLE public.organizer_verification_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organizer_profile_id BIGINT REFERENCES public.organizer_profiles(id) ON DELETE CASCADE,
  document_url VARCHAR(255),
  status verification_status DEFAULT 'pending',
  reviewed_by_user_id UUID REFERENCES public.users(id) ON DELETE SET NULL
);

-- Events Table
CREATE TABLE public.events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submitted_by_user_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  organizer_profile_id BIGINT REFERENCES public.organizer_profiles(id) ON DELETE SET NULL,
  external_organizer_name VARCHAR(255),
  title VARCHAR(255) NOT NULL,
  start_time TIMESTAMPTZ,
  location VARCHAR(255),
  source event_source DEFAULT 'user_submission',
  approval_status verification_status DEFAULT 'pending',
  reviewed_by_user_id UUID REFERENCES public.users(id) ON DELETE SET NULL
);

-- Event Announcements Table
CREATE TABLE public.event_announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT REFERENCES public.events(id) ON DELETE CASCADE,
  sender_user_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  title VARCHAR(255) NOT NULL,
  body TEXT
);

-- Table for RSVPs
CREATE TABLE public.rsvps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES public.users(id) ON DELETE CASCADE,
  event_id BIGINT REFERENCES public.events(id) ON DELETE CASCADE,
  status rsvp_status DEFAULT 'going',
  CONSTRAINT unique_user_event_rsvp UNIQUE (user_id, event_id)
);

-- Saved Events Table
CREATE TABLE public.saved_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES public.users(id) ON DELETE CASCADE,
  event_id BIGINT REFERENCES public.events(id) ON DELETE CASCADE,
  CONSTRAINT unique_user_saved_event UNIQUE (user_id, event_id)
);

-- Conversations Table - The purpose of this is to have a thread of messages.
CREATE TABLE public.conversations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attendee_user_id UUID REFERENCES public.users(id) ON DELETE CASCADE,
  organizer_profile_id BIGINT REFERENCES public.organizer_profiles(id) ON DELETE CASCADE,
  event_id BIGINT REFERENCES public.events(id) ON DELETE CASCADE
);

-- Messages Table
CREATE TABLE public.messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT REFERENCES public.conversations(id) ON DELETE CASCADE,
  sender_user_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  body TEXT
);