CREATE TABLE public.event_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
  image_url TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX event_images_event_id_idx ON public.event_images (event_id, id);

ALTER TABLE public.event_images ENABLE ROW LEVEL SECURITY;

CREATE POLICY event_images_read_visible_events ON public.event_images
  FOR SELECT TO anon, authenticated
  USING (EXISTS (SELECT 1 FROM public.events e WHERE e.id = event_id));

CREATE OR REPLACE FUNCTION public.add_event_image(p_event_id BIGINT, p_image_url TEXT)
RETURNS TABLE (id BIGINT, image_url TEXT)
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  submitter UUID;
BEGIN
  SELECT e.submitted_by_user_id INTO submitter FROM public.events e WHERE e.id = p_event_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Event not found' USING ERRCODE = 'EF404';
  END IF;
  IF submitter IS DISTINCT FROM (SELECT auth.uid()) THEN
    RAISE EXCEPTION 'Only the person who submitted this event can change its photos' USING ERRCODE = 'EF403';
  END IF;
  IF (SELECT count(*) FROM public.event_images i WHERE i.event_id = p_event_id) >= 6 THEN
    RAISE EXCEPTION 'An event can have up to 6 photos' USING ERRCODE = 'EF409';
  END IF;

  RETURN QUERY
  INSERT INTO public.event_images AS i (event_id, image_url)
  VALUES (p_event_id, p_image_url)
  RETURNING i.id, i.image_url;
END;
$$;

CREATE OR REPLACE FUNCTION public.remove_event_image(p_event_id BIGINT, p_image_id BIGINT)
RETURNS TEXT
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  submitter UUID;
  removed_url TEXT;
BEGIN
  SELECT e.submitted_by_user_id INTO submitter FROM public.events e WHERE e.id = p_event_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Event not found' USING ERRCODE = 'EF404';
  END IF;
  IF submitter IS DISTINCT FROM (SELECT auth.uid()) THEN
    RAISE EXCEPTION 'Only the person who submitted this event can change its photos' USING ERRCODE = 'EF403';
  END IF;

  DELETE FROM public.event_images i
  WHERE i.id = p_image_id AND i.event_id = p_event_id
  RETURNING i.image_url INTO removed_url;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Photo not found' USING ERRCODE = 'EF404';
  END IF;
  RETURN removed_url;
END;
$$;

REVOKE ALL ON FUNCTION public.add_event_image(BIGINT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.add_event_image(BIGINT, TEXT) TO authenticated;
REVOKE ALL ON FUNCTION public.remove_event_image(BIGINT, BIGINT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.remove_event_image(BIGINT, BIGINT) TO authenticated;
